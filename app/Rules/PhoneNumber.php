<?php

namespace App\Rules;

use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * رقم هاتف صالح — محليّ أو دوليّ، لكن لدولةٍ موجودة فعلاً.
 *
 * القاعدة السابقة كانت تقبل أي سبع خانات بعد `+`، فيمرّ `+99999999`
 * و`+00000000` بلا اعتراض. ورقمٌ خاطئ لا يظهر خطؤه عند الإدخال، بل يوم
 * تحتاج المدرسة أن تتّصل بأهل طالب غائب فلا تجد رقماً يعمل.
 *
 * ما يُقبل:
 * - محليّ: `0955123456` — يُفهم برمز دولة المدرسة، فلا تُطالَب المدرسة
 *   بكتابة رمز الدولة في كل مرّة.
 * - دوليّ: `+963955123456` أو `00963955123456` — ويُتحقّق أن البادئة رمزُ
 *   اتّصالٍ مخصَّص فعلاً (ITU-T E.164).
 *
 * المسافات والشُرَط والأقواس تُتجاهَل: من ينسخ رقماً من رسالة لا ينبغي أن
 * يُطالَب بتنظيفه أوّلاً.
 */
class PhoneNumber implements ValidationRule
{
    /**
     * رموز الاتّصال الدولية المخصَّصة (ITU-T E.164).
     *
     * تُطابَق بأطول بادئة: `1` لأمريكا الشمالية و`123` ليس رمزاً، فلولا
     * ترتيب الطول لقُبل كلّ ما يبدأ بواحد.
     *
     * @var array<int, string>
     */
    private const CALLING_CODES = [
        '1', '7', '20', '27', '30', '31', '32', '33', '34', '36', '39', '40', '41',
        '43', '44', '45', '46', '47', '48', '49', '51', '52', '53', '54', '55',
        '56', '57', '58', '60', '61', '62', '63', '64', '65', '66', '81', '82',
