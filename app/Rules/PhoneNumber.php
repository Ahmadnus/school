        '670', '672', '673', '674', '675', '676', '677', '678', '679', '680',
        '681', '682', '683', '685', '686', '687', '688', '689', '690', '691', '692',
        '850', '852', '853', '855', '856', '880', '886',
        '960', '961', '962', '963', '964', '965', '966', '967', '968',
        '970', '971', '972', '973', '974', '975', '976', '977', '992', '993',
        '994', '995', '996', '998',
    ];

    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        $digits = preg_replace('/[\s\-().\/]/', '', (string) $value);

        // `00` بادئة دوليّة في معظم العالم، فتُعامَل معاملة `+`.
        if (str_starts_with($digits, '00')) {
            $digits = '+'.substr($digits, 2);
        }

        if (! str_starts_with($digits, '+')) {
            // محليّ: الطول وحده هو المعيار؛ رمز الدولة يأتي من المدرسة.
            if (! preg_match('/^[0-9]{6,15}$/', $digits)) {
                $fail(__('validation.phone_number'));
            }

            return;
        }

        $national = substr($digits, 1);

        // لا يبدأ رقمٌ دوليّ بصفر، وطوله بين ٧ و١٥ خانة (E.164).
        if (! preg_match('/^[1-9][0-9]{6,14}$/', $national)) {
            $fail(__('validation.phone_number'));

            return;
        }

        if (self::countryCodeOf($national) === null) {
            $fail(__('validation.phone_number'));
        }
    }

    /** أطول بادئة تُطابق رمزاً مخصَّصاً، أو `null` إن لم تُطابق شيئاً. */
    private static function countryCodeOf(string $national): ?string
    {
        foreach ([3, 2, 1] as $length) {
            $prefix = substr($national, 0, $length);

            if (in_array($prefix, self::CALLING_CODES, true)) {
                return $prefix;
            }
        }

        return null;
    }
}
